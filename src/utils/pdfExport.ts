import jsPDF from 'jspdf';
import { BusinessProfile, MatchedOpportunity } from '../types';

export function generateMatchedSchemesPDF(
  profile: BusinessProfile,
  matches: MatchedOpportunity[]
) {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4'
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  let y = 16;

  // Header Banner
  doc.setFillColor(15, 23, 42); // slate-900
  doc.rect(0, 0, pageWidth, 28, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.text('ArthaAI — MSME Scheme Discovery & Action Plan Report', 14, 12);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(147, 197, 253); // blue-300
  doc.text('National Scheme Facilitation Gateway • Powered by ArthaAI Matching Engine', 14, 19);
  doc.text(`Generated: ${new Date().toLocaleDateString('en-IN', { day: 'numeric', month: 'short', year: 'numeric' })}`, pageWidth - 55, 19);

  y = 36;

  // Business Profile Summary Box
  doc.setFillColor(248, 250, 252); // slate-50
  doc.setDrawColor(226, 232, 240); // slate-200
  doc.roundedRect(14, y, pageWidth - 28, 26, 2, 2, 'FD');

  doc.setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.text(`Enterprise: ${profile.name}`, 18, y + 7);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.setTextColor(71, 85, 105);
  doc.text(`Sector: ${profile.industry}`, 18, y + 14);
  doc.text(`Location: ${profile.city}, ${profile.state}`, 18, y + 20);

  doc.text(`Turnover Tier: ${profile.turnover_band}`, 110, y + 14);
  doc.text(`Udyam: ${profile.udyam_registered ? 'Yes (Verified)' : 'No'} | GST: ${profile.gst_registered ? 'Yes' : 'No'}`, 110, y + 20);

  y += 34;

  // Matched Opportunities Header
  doc.setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.text(`Matched Government Schemes & Subsidies (${matches.length})`, 14, y);
  y += 6;

  // Render each match card
  matches.forEach((scheme, idx) => {
    // Check if we need a new page
    if (y > 240) {
      doc.addPage();
      y = 20;
    }

    doc.setFillColor(255, 255, 255);
    doc.setDrawColor(203, 213, 225); // slate-300
    doc.roundedRect(14, y, pageWidth - 28, 38, 2, 2, 'FD');

    // Category Pill & Score
    doc.setFillColor(30, 58, 138); // blue-900
    doc.roundedRect(18, y + 4, 26, 5, 1, 1, 'F');
    doc.setTextColor(255, 255, 255);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(7);
    doc.text(scheme.category.toUpperCase(), 20, y + 7.5);

    doc.setTextColor(5, 150, 105); // emerald-600
    doc.text(`${scheme.match_score}% MATCH`, pageWidth - 42, y + 7.5);

    // Scheme Name
    doc.setTextColor(15, 23, 42);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(9.5);
    doc.text(`${idx + 1}. ${scheme.name}`, 18, y + 14, { maxWidth: pageWidth - 40 });

    // Financial Benefit
    doc.setTextColor(4, 120, 87); // emerald-700
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8);
    doc.text(`Financial Benefit: ${scheme.benefit_value}`, 18, y + 20, { maxWidth: pageWidth - 40 });

    // Why You Qualify
    doc.setTextColor(51, 65, 85);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.text(`Why You Qualify: ${scheme.match_reason}`, 18, y + 26, { maxWidth: pageWidth - 40 });

    // Nodal Portal & Deadline
    doc.setTextColor(100, 116, 139);
    doc.setFontSize(7.5);
    doc.text(`Nodal Agency / Portal: ${scheme.official_url} | Deadline: ${scheme.deadline}`, 18, y + 33);

    y += 42;
  });

  // Footer on last page
  if (y > 260) {
    doc.addPage();
    y = 20;
  }

  doc.setTextColor(148, 163, 184);
  doc.setFont('helvetica', 'italic');
  doc.setFontSize(7.5);
  doc.text('Note: This report is generated by ArthaAI for preliminary eligibility guidance. Direct applications must be submitted via official state and central portals.', 14, y + 10, { maxWidth: pageWidth - 28 });

  // Save the PDF
  const sanitizedName = profile.name.replace(/[^a-zA-Z0-9]/g, '_').toLowerCase();
  doc.save(`ArthaAI_Schemes_${sanitizedName}.pdf`);
}
